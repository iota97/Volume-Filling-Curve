std::vector<std::array<Vec3Idx, 3>> marchingCube(const std::function<float(size_t, size_t, size_t)> &value, std::array<size_t, 3> domainSize, float cellSize, float quiet) {
    Vec3 offset = Vec3(0.5f*cellSize);
    std::vector<std::array<Vec3Idx, 3>> triangles;
    std::map<std::array<std::array<size_t, 3>, 2>, size_t> idxMap;
    for (size_t x = 0; x < domainSize[0]-1; ++x) {
        if (!quiet) printProgress(float(x+1)/(domainSize[0]-1));
        for(size_t y = 0; y < domainSize[1]-1; ++y) {
            for (size_t z = 0; z < domainSize[2]-1; ++z) {
                size_t idx = 0;
                for (uint8_t i = 0; i < 8; ++i) {
                    size_t px = x+vertices[i][0], py = y+vertices[i][1], pz = z+vertices[i][2];
                    float val = value(px, py, pz);
                    idx |= (val >= 0) << i;
                }

                for (std::array<uint8_t, 3> &tris : cases[idx]) {
                    std::array<uint8_t, 2> a = edges[tris[0]], b = edges[tris[1]], c = edges[tris[2]];
                    std::array<size_t, 3> ca0{x + vertices[a[0]][0], y + vertices[a[0]][1], z + vertices[a[0]][2]};
                    std::array<size_t, 3> ca1{x + vertices[a[1]][0], y + vertices[a[1]][1], z + vertices[a[1]][2]};
                    std::array<size_t, 3> cb0{x + vertices[b[0]][0], y + vertices[b[0]][1], z + vertices[b[0]][2]};
                    std::array<size_t, 3> cb1{x + vertices[b[1]][0], y + vertices[b[1]][1], z + vertices[b[1]][2]}; 
                    std::array<size_t, 3> cc0{x + vertices[c[0]][0], y + vertices[c[0]][1], z + vertices[c[0]][2]};
                    std::array<size_t, 3> cc1{x + vertices[c[1]][0], y + vertices[c[1]][1], z + vertices[c[1]][2]};
                    if (ca0 > ca1) std::swap(ca0, ca1);
                    if (cb0 > cb1) std::swap(cb0, cb1);
                    if (cc0 > cc1) std::swap(cc0, cc1);
                    Vec3 pa0 = cellSize*Vec3(ca0[0], ca0[1], ca0[2]);
                    Vec3 pa1 = cellSize*Vec3(ca1[0], ca1[1], ca1[2]);
                    Vec3 pb0 = cellSize*Vec3(cb0[0], cb0[1], cb0[2]);
                    Vec3 pb1 = cellSize*Vec3(cb1[0], cb1[1], cb1[2]);
                    Vec3 pc0 = cellSize*Vec3(cc0[0], cc0[1], cc0[2]);
                    Vec3 pc1 = cellSize*Vec3(cc1[0], cc1[1], cc1[2]);
                    float va0 = value(ca0[0], ca0[1], ca0[2]);
                    float va1 = value(ca1[0], ca1[1], ca1[2]);
                    float vb0 = value(cb0[0], cb0[1], cb0[2]);
                    float vb1 = value(cb1[0], cb1[1], cb1[2]);
                    float vc0 = value(cc0[0], cc0[1], cc0[2]);
                    float vc1 = value(cc1[0], cc1[1], cc1[2]);
                    if (fabsf(va0) < 1e-3) va0 = va0 >= 0 ? 1e-3 : -1e-3; 
                    if (fabsf(va1) < 1e-3) va1 = va1 >= 0 ? 1e-3 : -1e-3; 
                    if (fabsf(vb0) < 1e-3) vb0 = vb0 >= 0 ? 1e-3 : -1e-3; 
                    if (fabsf(vb1) < 1e-3) vb1 = vb1 >= 0 ? 1e-3 : -1e-3;
                    if (fabsf(vc0) < 1e-3) vc0 = vc0 >= 0 ? 1e-3 : -1e-3; 
                    if (fabsf(vc1) < 1e-3) vc1 = vc1 >= 0 ? 1e-3 : -1e-3;
                    
                    std::array<std::array<size_t, 3>, 2> ea{ca0, ca1};
                    std::array<std::array<size_t, 3>, 2> eb{cb0, cb1};
                    std::array<std::array<size_t, 3>, 2> ec{cc0, cc1};

                    size_t idxA, idxB, idxC;
                    if (idxMap.count(ea)) {
                        idxA = idxMap[ea];
                    } else {
                        idxA = idxMap.size();
                        idxMap[ea] = idxA; 
                    }

                    if (idxMap.count(eb)) {
                        idxB = idxMap[eb];
                    } else {
                        idxB = idxMap.size();
                        idxMap[eb] = idxB; 
                    }

                    if (idxMap.count(ec)) {
                        idxC = idxMap[ec];
                    } else {
                        idxC = idxMap.size();
                        idxMap[ec] = idxC; 
                    }

                    Vec3Idx va{ pa0-va0/(va1-va0)*(pa1-pa0) + offset, idxA};
                    Vec3Idx vb{ pb0-vb0/(vb1-vb0)*(pb1-pb0) + offset, idxB};
                    Vec3Idx vc{ pc0-vc0/(vc1-vc0)*(pc1-pc0) + offset, idxC};

                    triangles.push_back({va, vb, vc});
                } 
            }
        }
    }
    
    return triangles;
}

void saveTriangleToPLY(const char *path, const  std::vector<std::array<Vec3Idx, 3>> &triangles, const Vec3 &offset) {
    size_t vertsCount = 0;
    for (const auto &t : triangles) {
        vertsCount = std::max(vertsCount, t[0].idx + 1);
        vertsCount = std::max(vertsCount, t[1].idx + 1);
        vertsCount = std::max(vertsCount, t[2].idx + 1);
    }

    std::vector<Vec3> verts(vertsCount);
    for (const auto &t : triangles) {
        verts[t[0].idx] = t[0].v;
        verts[t[1].idx] = t[1].v;
        verts[t[2].idx] = t[2].v;
    }

    std::ofstream plyFile(path);
    plyFile << "ply\nformat ascii 1.0\nelement vertex " << vertsCount << "\n"
            << "property float x\nproperty float y\nproperty float z\n"
            << "element face " << triangles.size() << "\nproperty list uchar uint vertex_indices\n"
            << "end_header\n";
        
    for (const auto &v : verts) {
        plyFile << v.x + offset.x << " " << v.y + offset.y << " " << v.z + offset.z << std::endl;
    }

    for (const auto &t : triangles) {
        plyFile << "3 " << t[0].idx << " " << t[1].idx << " " << t[2].idx << std::endl;
    }
}

void saveTriangleToViridisPLY(const char *path, const  std::vector<std::array<Vec3Idx, 3>> &triangles, const Vec3 &offset, const std::function<float(Vec3)> &value) {
    size_t vertsCount = 0;
    for (const auto &t : triangles) {
        vertsCount = std::max(vertsCount, t[0].idx + 1);
        vertsCount = std::max(vertsCount, t[1].idx + 1);
        vertsCount = std::max(vertsCount, t[2].idx + 1);
    }

    std::vector<Vec3> verts(vertsCount);
    std::vector<std::array<uint8_t, 3>> colors(vertsCount);
    for (const auto &t : triangles) {
        verts[t[0].idx] = t[0].v;
        verts[t[1].idx] = t[1].v;
        verts[t[2].idx] = t[2].v;
    }
    for (size_t i = 0; i < vertsCount; ++i) {
        colors[i] = viridis(0.5f*value(verts[i])+0.5f);
    }

    std::ofstream plyFile(path);
    plyFile << "ply\nformat ascii 1.0\nelement vertex " << vertsCount << "\n"
            << "property float x\nproperty float y\nproperty float z\n"
            << "property uchar red\nproperty uchar green\nproperty uchar blue\n"
            << "element face " << triangles.size() << "\nproperty list uchar uint vertex_indices\n"
            << "end_header\n";
        
    for (size_t i = 0; i < vertsCount; ++i) {
        plyFile << verts[i].x + offset.x << " " << verts[i].y + offset.y << " " << verts[i].z + offset.z << " "
                << uint32_t(colors[i][0]) << " " << uint32_t(colors[i][1]) << " " << uint32_t(colors[i][2]) << std::endl;
    }

    for (const auto &t : triangles) {
        plyFile << "3 " << t[0].idx << " " << t[1].idx << " " << t[2].idx << std::endl;
    }
}
